from __future__ import annotations

import dataclasses
import os
from dataclasses import dataclass, field
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()

ENV_PATH = Path(os.getenv("ENV_FILE_PATH", ".env"))


def _env_str(key: str, default: str = "") -> dataclasses.Field:
    return field(default_factory=lambda: os.getenv(key, default))


def _env_int(key: str, default: int) -> dataclasses.Field:
    return field(default_factory=lambda: int(os.getenv(key, str(default))))


@dataclass
class Settings:
    """Platform-level configuration, shared by every tenant. Never exposed to
    end users - only the operator running this service touches these, via .env."""

    # Every post (research, title, caption, hashtags, script) is written by Claude.
    anthropic_api_key: str = _env_str("ANTHROPIC_API_KEY")
    anthropic_model: str = _env_str("ANTHROPIC_MODEL", "claude-sonnet-5-5")

    # Post images are generated by Gemini from a Claude-written prompt. Without
    # a Gemini key, posts fall back to a real Pexels stock photo + headline.
    gemini_api_key: str = _env_str("GEMINI_API_KEY")
    gemini_image_model: str = _env_str("GEMINI_IMAGE_MODEL", "gemini-nano-banana-2.1")
    gemini_image_size: str = _env_str("GEMINI_IMAGE_SIZE", "2K")  # 1K | 2K | 4K
    pexels_api_key: str = _env_str("PEXELS_API_KEY")


    meta_app_id: str = _env_str("META_APP_ID")
    meta_app_secret: str = _env_str("META_APP_SECRET")

    # Instagram Business Login uses a *different* App ID/Secret than the main
    # Meta app - found in App Dashboard > Instagram > API setup with
    # Instagram login > "3. Set up Instagram business login" > Business
    # login settings. Using meta_app_id/secret here fails with "Invalid
    # platform app" - that pair is for Facebook Login (below), not this.
    instagram_app_id: str = _env_str("INSTAGRAM_APP_ID")
    instagram_app_secret: str = _env_str("INSTAGRAM_APP_SECRET")
    instagram_graph_api_version: str = _env_str("INSTAGRAM_GRAPH_API_VERSION", "v25.0")
    instagram_oauth_redirect_uri: str = _env_str("INSTAGRAM_OAUTH_REDIRECT_URI")

    # Facebook Page publishing uses the main Meta app id/secret above (regular
    # Facebook Login, not Instagram Business Login) - just a different OAuth
    # scope set and a Page access token instead of an IG user token.
    facebook_graph_api_version: str = _env_str("FACEBOOK_GRAPH_API_VERSION", "v25.0")
    facebook_oauth_redirect_uri: str = _env_str("FACEBOOK_OAUTH_REDIRECT_URI")

    # LinkedIn is a separate developer app (own client id/secret) - posts to
    # the connecting member's own profile (w_member_social via "Share on
    # LinkedIn", self-serve). Company Page posting needs Community Management
    # API, which requires LinkedIn's review, so it's intentionally not built.
    linkedin_client_id: str = _env_str("LINKEDIN_CLIENT_ID")
    linkedin_client_secret: str = _env_str("LINKEDIN_CLIENT_SECRET")
    linkedin_oauth_redirect_uri: str = _env_str("LINKEDIN_OAUTH_REDIRECT_URI")
    linkedin_api_version: str = _env_str("LINKEDIN_API_VERSION", "202608")

    # TikTok - self-serve app creation and connect/post work immediately, but
    # until the app passes TikTok's audit, every post is forced to SELF_ONLY
    # (private) visibility server-side - that's enforced by TikTok, not
    # something this app's code controls.
    tiktok_client_key: str = _env_str("TIKTOK_CLIENT_KEY")
    tiktok_client_secret: str = _env_str("TIKTOK_CLIENT_SECRET")
    tiktok_oauth_redirect_uri: str = _env_str("TIKTOK_OAUTH_REDIRECT_URI")

    # X (Twitter) - OAuth 2.0 with PKCE, self-serve app creation. Posts to the
    # connecting user's own account. Access tokens are short-lived (~2h) with
    # a refresh_token (offline.access scope), refreshed before each publish
    # attempt the same way TikTok's is.
    x_client_id: str = _env_str("X_CLIENT_ID")
    x_client_secret: str = _env_str("X_CLIENT_SECRET")
    x_oauth_redirect_uri: str = _env_str("X_OAUTH_REDIRECT_URI")

    # YouTube - Google Cloud Console OAuth client (self-serve, but the app
    # needs Google's verification before youtube.upload works for anyone
    # other than the 100 test users added in the OAuth consent screen while
    # "Testing"). access_type=offline + prompt=consent at connect time is
    # what makes Google issue a refresh_token - access tokens only last ~1h,
    # refreshed before each publish the same way TikTok/X are.
    youtube_client_id: str = _env_str("YOUTUBE_CLIENT_ID")
    youtube_client_secret: str = _env_str("YOUTUBE_CLIENT_SECRET")
    youtube_oauth_redirect_uri: str = _env_str("YOUTUBE_OAUTH_REDIRECT_URI")

    storage_endpoint_url: str = _env_str("STORAGE_ENDPOINT_URL")
    storage_bucket: str = _env_str("STORAGE_BUCKET")
    storage_access_key_id: str = _env_str("STORAGE_ACCESS_KEY_ID")
    storage_secret_access_key: str = _env_str("STORAGE_SECRET_ACCESS_KEY")
    storage_public_base_url: str = _env_str("STORAGE_PUBLIC_BASE_URL")
    storage_region: str = _env_str("STORAGE_REGION", "auto")

    database_url: str = _env_str("DATABASE_URL", "sqlite:///./data/app.db")
    video_gen_lead_days: int = _env_int("VIDEO_GEN_LEAD_DAYS", 2)
    max_auto_retries: int = _env_int("MAX_AUTO_RETRIES", 2)

    session_secret: str = _env_str("SESSION_SECRET")

    # Shown on the public /terms and /privacy pages - platform app reviews
    # (Google, Meta, TikTok) require a real contact and operator name there.
    legal_operator_name: str = _env_str("LEGAL_OPERATOR_NAME", "Reelmind")
    legal_contact_email: str = _env_str("LEGAL_CONTACT_EMAIL")


settings = Settings()
